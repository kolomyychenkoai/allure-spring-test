#!/usr/bin/env bash
#
# Общий кусок для скриптов: найти review-tools.jar или понятно объяснить, чего нет.
# Не самостоятельный скрипт — его подключают через `source`.
#
# Зачем отдельно. Раньше проверка предусловия была ровно в ОДНОМ месте из пяти: report-tree.sh
# честно говорил «нужен python3», остальные падали как получится — трассой интерпретатора
# или пустым выводом, из которого не понять, сломался инструмент или данных нет.
# Теперь ответ один и тот же во всех местах.
#
# Даёт: TOOLS_JAR (путь) и функцию tools (запуск подкоманды).
#
# Кодировку вывода jar задаёт сам и от локали вызывающего не зависит — почему именно так,
# написано в ReviewTools.main().

TOOLS_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")/../tools" && pwd)
TOOLS_JAR="$TOOLS_DIR/target/review-tools.jar"

require_tools() {
    command -v java >/dev/null 2>&1 || {
        echo "нужен java (JDK) — им собран и сам проект" >&2
        exit 2
    }
    [ -f "$TOOLS_JAR" ] || {
        echo "нет $TOOLS_JAR — собери инструменты:" >&2
        echo "    (cd tools && mvn -q package)" >&2
        echo "Это отдельный проект, а не модуль библиотеки: он собирается, даже когда" >&2
        echo "библиотека не компилируется — диагностика нужна именно в такие моменты." >&2
        exit 2
    }

    # Устаревший jar — ложно-зелёное того же рода, что и сломавшийся сбор: правку внесли,
    # пересобрать забыли, инструмент показывает прежнее поведение и молчит об этом.
    local newer
    newer=$(find "$TOOLS_DIR/src" "$TOOLS_DIR/pom.xml" -newer "$TOOLS_JAR" 2>/dev/null | head -1)
    [ -z "$newer" ] || {
        echo "$TOOLS_JAR старее исходников (например $newer) — пересобери:" >&2
        echo "    (cd tools && mvn -q package)" >&2
        exit 2
    }
}

# tools <подкоманда> [аргументы…]
tools() {
    require_tools
    java -jar "$TOOLS_JAR" "$@"
}
