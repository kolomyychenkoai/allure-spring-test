#!/usr/bin/env bash
#
# Механика прохода 2.9 из docs/review-playbook.md: собирает ВСЁ, что нужно прочитать
# и посчитать по оси «комментарии». Думать по-прежнему человеку — скрипт убирает
# «забыл проход» и делает сплошное чтение дешёвым.
#
# Почему одних грепов мало. Греп закрывает правила 1, 7, 9, 10 код-стандарта (история,
# оценки, TODO, объём). Правила 2, 3 и 5 — пересказ соседнего кода, один факт в нескольких
# местах, непроверенное число — грепом не берутся: их видно только чтением. Поэтому главная
# секция здесь не грепы, а ПЕЧАТЬ ВСЕХ добавленных строк комментариев подряд.
#
# Использование:  scripts/comment-scan.sh [база]      (по умолчанию origin/main)
#
set -u
cd "$(dirname "$0")/.." || exit 2

# ⚠️ Байтовая локаль обязательна: BSD sed на macOS в UTF-8-локали падает на кириллице
# («illegal byte sequence»), и ГЛАВНАЯ секция — сплошное чтение — молча остаётся пустой.
# Пустая секция тут читается как «комментариев не добавляли», то есть проход врёт.
export LC_ALL=C

BASE=${1:-origin/main}
# Диапазон БЕЗ ...HEAD: так в диф попадает и рабочее дерево, иначе проход не увидит
# как раз ту работу, которую сейчас и проверяешь.
RANGE=$(git merge-base "$BASE" HEAD 2>/dev/null || echo "$BASE")
SRC=(src scripts docs README.md)

hdr() { printf '\n\033[1m%s\033[0m\n%s\n' "$1" "$(printf '─%.0s' $(seq 1 ${#1}))"; }

# Пустая секция ОБЪЯВЛЯЕТСЯ: молчание неотличимо от сломавшегося сбора.
show() {
    local out
    out=$(cat)
    if [ -z "$out" ]; then printf '  (пусто)\n'; else printf '%s\n' "$out"; fi
}

# Добавленные строки комментариев кода: // /* * #  (шебанг не считаем).
added_comments() {
    git diff "$RANGE" -- src scripts | grep -E '^\+' | grep -vE '^\+\+\+' \
        | grep -E '^\+[[:space:]]*(//|/\*|\*|#)' | grep -vE '^\+#!'
}

echo "Скан комментариев: $RANGE (включая рабочее дерево)"

# ── Объём ────────────────────────────────────────────────────────────────────
# Цифра «сколько я насыпал» не видна ни автору, ни ревьюеру, пока её не посчитать.
# Она же — единственный измеримый результат прохода: «было N, стало M».
hdr "1. ОБЪЁМ: строк комментариев добавлено (по файлам)"
for f in $(git diff --name-only "$RANGE" -- src scripts); do
    [ -f "$f" ] || continue
    n=$(git diff "$RANGE" -- "$f" | grep -E '^\+' | grep -vE '^\+\+\+' \
        | grep -cE '^\+[[:space:]]*(//|/\*|\*|#)')
    [ "$n" -gt 0 ] && printf '  %4s  %s\n' "$n" "$f"
done | sort -rn | show
printf '  ─────\n  %4s  ВСЕГО\n' "$(added_comments | wc -l | tr -d ' ')"

# ── Сплошное чтение ──────────────────────────────────────────────────────────
# Главная секция. Правила 2/3/5 иначе не видны: пересказ соседнего javadoc и один факт
# в пяти файлах выглядят нормально в дифе по файлам и находятся только чтением подряд.
hdr "2. ПРОЧИТАТЬ ПОДРЯД: все добавленные строки комментариев"
added_comments | sed 's/^+/  /' | show

# ── Кандидаты на дубль между файлами ─────────────────────────────────────────
# Пары соседних слов, встретившиеся в комментариях РАЗНЫХ файлов. Это лупа, а не гейт:
# «общей точке» в двух местах бывает законно, но именно так выглядит факт, размазанный
# по репозиторию. Один факт — одно место, остальные ссылаются (§6, правило 3).
hdr "3. КАНДИДАТЫ НА ДУБЛЬ: пары слов в комментариях 2+ файлов"
git diff "$RANGE" -- src scripts | awk '
    /^\+\+\+ b\// { file = substr($2, 3); next }
    /^\+[ \t]*(\/\/|\/\*|\*|#)/ {
        line = $0
        gsub(/[.,;:()«»"\047`—–\-]/, " ", line)
        n = split(line, w, /[ \t]+/)
        prev = ""
        for (i = 1; i <= n; i++) {
            if (length(w[i]) < 8) { prev = ""; continue }   # 8 БАЙТ ≈ 4 буквы кириллицы
            if (prev != "") {
                key = prev " " w[i]
                if (!((key SUBSEP file) in seen)) { seen[key, file] = 1; cnt[key]++ }
            }
            prev = w[i]
        }
    }
    END { for (k in cnt) if (cnt[k] >= 2) printf "  %d файла: %s\n", cnt[k], k }
' | sort -rn | head -20 | show

# ── Грепы правил, которые греп берёт ─────────────────────────────────────────
# Шаблоны сужены до тех, что почти не дают ложных: «ревью» и «однажды» сами по себе
# встречаются в механике («процедура ревью», «эвристика однажды совпадёт»), и секция,
# которая шумит, обучает себя пролистывать.
hdr "4. Правило 1: история вместо механики"
added_comments | grep -inE '(раньше|теперь |было:|стало |PR #|в коммите|однажды уже|прошлый раз|показал, что|нашла |нашёл )' | show

hdr "5. Правило 7: оценки и разговорное"
added_comments | grep -inE '(беда|больно|коварн|магия|костыл|увы|почему-то|к сожалению)' | show

hdr "6. Правило 9: TODO / FIXME / закомментированный код"
added_comments | grep -inE 'TODO|FIXME|^\+[[:space:]]*//[[:space:]]*[a-zA-Zа-яА-Я_]+\(' | show

hdr "7. Правило 10: блоки ИНЛАЙН-комментариев (//) длиннее 3 строк"
# Только `//` в коде. javadoc исключён намеренно (правило 10 разрешает там объём),
# шапки скриптов на `#` — тоже: это условия запуска инструмента, а не пояснение к строке.
# Диф отдаём awk СЫРЫМ: если отфильтровать контекстные строки заранее, два соседних
# трёхстрочных комментария из разных методов склеятся в один «блок из 6» — ложная находка.
git diff "$RANGE" -- src \
    | awk '/^\+\+\+/ { n = 0; next }
           /^\+[ \t]*\/\// { n++; if (n == 4) first = $0; next }
           { if (n > 3) printf "  блок из %d строк: %s…\n", n, substr(first, 1, 70); n = 0 }
           END { if (n > 3) printf "  блок из %d строк\n", n }' | show

cat <<'HINT'

Чего скрипт сделать не может — и без чего проход НЕ закрыт (docs/review-playbook.md, 2.9).
Ответить письменно:
  1. какой факт написан больше одного раза — и в каком файле он остаётся каноническим;
  2. какая строка пересказывает соседний код или чужой javadoc;
  3. какое утверждение (число, версия, имя типа) не перемерено сейчас;
  4. сколько строк комментариев было и сколько стало.

Числовые утверждения по всему дифу — секция 1 в scripts/review-scan.sh.
HINT
