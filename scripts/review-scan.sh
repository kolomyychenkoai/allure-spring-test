#!/usr/bin/env bash
#
# Механика проходов из docs/review-playbook.md: собирает СПИСКИ, которые ревьюер обязан
# просмотреть. Думать по-прежнему человеку — скрипт лишь убирает «забыл проход».
#
# Половина проходов playbook — это сбор списков, а не мышление: удалённые строки,
# call sites изменённых общих точек, числовые утверждения в комментариях, обещания
# в доках, новые гейты без мутации. Ровно на них и держались пропуски.
#
# Использование:  scripts/review-scan.sh [база]      (по умолчанию origin/main)
#
set -u
cd "$(dirname "$0")/.." || exit 2

BASE=${1:-origin/main}
RANGE="$BASE...HEAD"

hdr() { printf '\n\033[1m%s\033[0m\n%s\n' "$1" "$(printf '─%.0s' $(seq 1 ${#1}))"; }

# Молча пустая секция читается как «тут ничего нет» — а на деле может значить «сбор сломался».
# Это ровно та болезнь, которую проект зовёт вечно-зелёным детектором, поэтому пустота
# ОБЪЯВЛЯЕТСЯ. Заодно считаем непустые секции: ноль находок на большом дифе — само по себе
# подозрительно и стоит проверки скрипта, а не вывода.
# Счётчик держим в ФАЙЛЕ, а не в переменной: show вызывается на конце пайпа, то есть в
# подоболочке — присваивание в ней родителю не видно, и счётчик молча остался бы нулём.
COUNTER=$(mktemp)
printf '0 0' > "$COUNTER"
trap 'rm -f "$COUNTER"' EXIT

show() {
    local out total found
    out=$(cat)
    read -r total found < "$COUNTER"
    total=$((total + 1))
    if [ -z "$out" ]; then
        printf '  (пусто)\n'
    else
        printf '%s\n' "$out"
        found=$((found + 1))
    fi
    printf '%s %s' "$total" "$found" > "$COUNTER"
}

echo "Скан ревью: $RANGE"

# ── 2.1 Перемер утверждений ──────────────────────────────────────────────────
# Числа в комментариях гниют быстрее кода: «сейчас подавляется ~47 сбоев» пережило
# правку, после которой их стало 2. Каждое число тут — кандидат на проверку командой.
hdr "1. Числовые утверждения в ДОБАВЛЕННЫХ комментариях (перемерить)"
git diff "$RANGE" -- src | grep -E "^\+" | grep -vE "^\+\+\+" \
    | grep -E "^\+\s*(\*|//)" | grep -E "[0-9]{2,}" | sed 's/^+/  /' | head -40 | show

# ── 2.2 Удалённые строки ─────────────────────────────────────────────────────
# Самый опасный класс правок — не новый код, а снятый гейт и смягчённый ассерт.
hdr "2. УДАЛЁННЫЕ строки кода (не комментарии, не импорты)"
git diff "$RANGE" -- src | grep -E "^-" | grep -vE "^---" \
    | grep -vE "^-\s*(\*|//|$)" | grep -vE "^-import" | sed 's/^-/  /' | head -40 | show

# ── 2.3 Call sites изменённых общих точек ────────────────────────────────────
# Диф покажет изменение функции, но не покажет, что у неё есть вызовы с ДРУГИМ смыслом.
# Самый дорогой дефект проекта нашёлся именно так.
hdr "3. Изменённые методы src/main и число их вызовов (смотреть КАЖДЫЙ)"
# Один sed вместо цепочки grep -o: цепочка отдаёт пусто внутри скрипта (работает только
# в интерактивном шелле), и проход существовал бы лишь на бумаге.
git diff "$RANGE" -- src/main \
    | sed -nE 's/^\+.*(public|protected|static)[^(]* ([a-z][A-Za-z0-9_]*)\(.*/\2/p' \
    | sort -u \
    | while read -r m; do
        [ -z "$m" ] && continue
        n=$(grep -rn "\.$m(" src --include='*.java' 2>/dev/null | wc -l | tr -d ' ')
        [ "$n" -gt 0 ] && printf '  %-28s вызовов: %s\n' "$m" "$n"
    done | head -30 | show

# ── Обещания без стража ──────────────────────────────────────────────────────
# «Никогда не роняем», «всегда включён» — это контракт. У контракта должен быть тест.
hdr "4. ОБЕЩАНИЯ в добавленных доках/комментариях (есть ли страж?)"
git diff "$RANGE" -- src docs README.md | grep -E "^\+" | grep -vE "^\+\+\+" \
    | grep -iE "никогда|всегда|гарантир|обязан|не роня" | sed 's/^+/  /' | head -25 | show

# ── Новые гейты как кандидаты на мутацию ─────────────────────────────────────
hdr "5. НОВЫЕ гейты (на каждый нужна мутация, которую видит ИМЕННО он)"
git diff "$RANGE" -- src/test | grep -E "^\+" \
    | grep -E "throw new AssertionError|require\(" | sed 's/^+/  /' | head -25 | show

# ── Синхронность артефактов ──────────────────────────────────────────────────
hdr "6. Синхронность артефактов"
for f in src/test/inventory/report-inventory.txt README.md docs/upgrade-checklist.md \
         docs/compat-matrix.md pom.xml; do
    if git diff --quiet "$RANGE" -- "$f"; then
        printf '  %-42s не менялся\n' "$f"
    else
        printf '  %-42s ИЗМЕНЁН — проверь, что числа и обещания сходятся\n' "$f"
    fi
done

read -r TOTAL FOUND < "$COUNTER"
printf '\n\033[1mИтог:\033[0m непустых секций %s из %s\n' "$FOUND" "$TOTAL"
if [ "$FOUND" -eq 0 ]; then
    echo "⚠️  НИ ОДНОЙ находки на всём дифе — так почти не бывает."
    echo "    Сперва проверь сам скрипт (сбор мог сломаться), потом уже радуйся."
fi

cat <<'HINT'

Дальше — то, что скрипт сделать не может:
  • открыть ТЕЛА вложений (target/allure-results/*-attachment.*), а не имена шагов;
  • задать каждому новому тесту вопрос «что сломать в src/main, чтобы он упал?»;
  • прогнать мутации (-Dmaven.test.failure.ignore=true и смотреть, КТО покраснел);
  • scripts/repeat.sh — если трогали тест-инфраструктуру.
HINT
