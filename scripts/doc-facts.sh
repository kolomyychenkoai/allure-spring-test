#!/usr/bin/env bash
#
# Отпечаток ФАКТОВ документа: числа, идентификаторы, пути, ссылки на разделы, заголовки,
# первые ячейки строк таблиц. Форма (слова, порядок предложений, эмфаза) в отпечаток не входит.
#
# Зачем. Стилевая правка обязана менять только форму. Проверять это чтением — то же самое,
# что породило правку: глаз видит текст, а не пропавшую строку таблицы. Поэтому снимаем
# отпечаток до и после и сравниваем.
#
# Использование:
#   scripts/doc-facts.sh docs/architecture.md                    # отпечаток рабочей копии
#   scripts/doc-facts.sh docs/architecture.md HEAD               # отпечаток из ревизии
#   diff <(scripts/doc-facts.sh ФАЙЛ HEAD) <(scripts/doc-facts.sh ФАЙЛ)   # пусто = смысл цел
#
set -u
cd "$(dirname "$0")/.." || exit 2

# Байтовая локаль: BSD sed/grep на кириллице в UTF-8-локали падают, и отпечаток молча
# оказался бы пустым — то есть «всё совпало» на сломанном сборе.
export LC_ALL=C

FILE=${1:?укажи файл, напр. docs/architecture.md}
REV=${2:-}

text() {
    if [ -n "$REV" ]; then git show "$REV:$FILE"; else cat "$FILE"; fi
}

BODY=$(text) || { echo "✗ не прочитать $FILE ${REV:+в ревизии $REV}"; exit 1; }
[ -n "$BODY" ] || { echo "✗ пусто: $FILE ${REV:+в ревизии $REV}"; exit 1; }

emit() { printf '%s\n' "$BODY" | eval "$1"; }

{
    # Заголовки с ПОРЯДКОВЫМ номером: порядок разделов — тоже факт. Нумеровать НОМЕРОМ СТРОКИ
    # нельзя: любая правка текста сдвигает строки ниже, и отпечаток расходился бы на каждой
    # стилевой правке — то есть шумел бы ровно там, где должен молчать (поймано мутацией).
    # Блоки ``` пропускаем: комментарий `# …` в bash — не заголовок (тоже поймано мутацией).
    emit "awk '/^\`\`\`/ { fence = !fence; next }
                !fence && /^#+ / { printf \"H%02d %s\\n\", ++n, \$0 }'"
    # Числа: любое число длиннее одной цифры (годы, объёмы, версии, счётчики).
    emit "grep -o '[0-9][0-9_ ]*[0-9]\\|[0-9]' | tr -d ' ' | sed 's/^/N /'"
    # Идентификаторы и пути в обратных кавычках — всё, на что документ ссылается.
    emit "grep -o '\`[^\`]*\`' | sed 's/^/I /'"
    # Ссылки на разделы.
    emit "grep -o '§[0-9]*' | sed 's/^/S /'"
    # Первая ячейка каждой строки таблицы: строка таблицы = факт, её пропажа = потеря смысла.
    emit "grep '^|' | grep -v '^|---' | awk -F'|' '{print \"T \" \$2}'"
} | sed 's/[[:space:]]\+$//' | sort | uniq -c | sed 's/^ *//'
