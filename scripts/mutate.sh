#!/usr/bin/env bash
#
# Проход 2.8 из docs/review-playbook.md: доказать гейт мутацией.
#
# Зачем отдельный инструмент — две причины, обе из живых провалов.
#
# 1. ОТКАТ МУТАЦИИ СНОСИТ НЕЗАКОММИЧЕННОЕ. Откат — это `git checkout` по файлу,
#    и вместе с мутацией он уносит всё, что в этом файле не закоммичено. В круге #74
#    так пропали правки двух файлов: первая нашлась сразу по ошибке компиляции,
#    вторая — только через два прогона, когда мутация на её гейт прошла вхолостую.
#    Между этим успел уйти коммит, обещавший откат ослабления, которого в нём не было.
#    Поэтому: на грязном дереве скрипт отказывается работать.
#
# 2. «ЧТО-ТО ПОКРАСНЕЛО» НЕ ЗНАЧИТ «ПОКРАСНЕЛ ТВОЙ ГЕЙТ». Без
#    -Dmaven.test.failure.ignore=true прогон падает на первом же красном и до поздних
#    гейтов дело не доходит, а красный в логе есть — и его легко принять за свой.
#    Скрипт всегда ставит этот флаг и печатает ИМЕНА покрасневших, а не факт красноты.
#
# 3. ОШИБКА КОМПИЛЯЦИИ — НЕ КРАСНЫЙ ТЕСТ. Сборка с -Werror валится на предупреждении,
#    и в логе это выглядит как «сборка упала» — то есть как успех мутации. Гейт при
#    этом не отработал вовсе: до тестов не дошли. Скрипт разводит эти два исхода.
#
# Использование:
#   scripts/mutate.sh <файл> <что-заменить> <на-что>
#
#   Заменяемое — ЛИТЕРАЛ (не регексп) и обязан встречаться в файле ровно один раз:
#   мутация, задевшая два места, доказывает не тот гейт. Многострочный литерал
#   передаётся в кавычках с переводами строк.
#
# Пример (мутация гейта числа тестов):
#   scripts/mutate.sh docs/testing.md 'Тестов в сьюте: 601' 'Тестов в сьюте: 600'
#
set -u
cd "$(dirname "$0")/.." || exit 2

if [ $# -ne 3 ]; then
    sed -n '2,33p' "$0" | sed 's/^# \{0,1\}//'
    exit 2
fi

FILE=$1
OLD=$2
NEW=$3

[ -f "$FILE" ] || { echo "нет такого файла: $FILE"; exit 2; }

# --- 1. Дерево обязано быть чистым -------------------------------------------------
dirty=$(git status --porcelain)
if [ -n "$dirty" ]; then
    echo "ОТКАЗ: дерево грязное — откат мутации унесёт незакоммиченное вместе с ней."
    echo
    echo "$dirty" | sed 's/^/    /'
    echo
    echo "Закоммить или спрячь (git stash), потом повторяй мутацию."
    exit 2
fi

. "$(dirname "$0")/require-jdk.sh"
require_jdk

LOG=.mutate.log

restore() {
    git checkout -- "$FILE" 2>/dev/null
}

# Итоговая строка surefire, а не построчная по классу: у per-class строк тот же формат
# плюс хвост «-- in <класс>», и tail по ним даёт число тестов последнего класса вместо
# итога прогона. Поймано на первой же мутации: «Tests run: 3» при 601 в сьюте.
summary() {
    grep -E 'Tests run: [0-9]+, Failures: [0-9]+, Errors: [0-9]+, Skipped: [0-9]+$' "$1" \
        | tail -1 | sed -E 's/^\[[A-Z]+\] //'
}
trap restore EXIT INT TERM

# --- 2. Применяем мутацию ----------------------------------------------------------
python3 - "$FILE" "$OLD" "$NEW" <<'PY' || exit 2
import sys
path, old, new = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(path, encoding='utf-8').read()
n = text.count(old)
if n != 1:
    print(f"ОТКАЗ: заменяемое встречается {n} раз(а), нужно ровно 1 — "
          f"мутация на два места доказывает не тот гейт.")
    sys.exit(2)
open(path, 'w', encoding='utf-8').write(text.replace(old, new))
PY

echo "Мутация в $FILE:"
git diff --unified=0 -- "$FILE" | grep -E '^[-+][^-+]' | sed 's/^/    /'
echo

# --- 3. Прогон -----------------------------------------------------------------------
# failure.ignore обязателен: без него до поздних гейтов дело не дойдёт (см. шапку).
started=$(date +%s)
mvn -B clean test -Dmaven.test.failure.ignore=true > "$LOG" 2>&1
echo "Прогон: $(( $(date +%s) - started ))s, лог в $LOG"
echo

# --- 4. Компиляция или тесты? --------------------------------------------------------
# Если тестов не запускалось вовсе — красный дала сборка, а не гейт.
if ! grep -qE '^\[INFO\] Tests run:|^Tests run:' "$LOG"; then
    echo "❌ МУТАЦИЯ НЕ ДОШЛА ДО ТЕСТОВ — сборка упала раньше."
    echo "   Это НЕ доказательство гейта: он не отработал ни разу."
    grep -E '^\[ERROR\].*\.java|^\[ERROR\] COMPILATION|warnings found' "$LOG" \
        | head -10 | sed 's/^/    /'
    echo
    echo "   Переформулируй мутацию так, чтобы код собирался."
    exit 3
fi

# --- 5. Кто именно покраснел ---------------------------------------------------------
# Смотреть надо ИМЕНА и ЧИСЛА: «в логе есть красный» — не ответ.
reds=$(grep -E '^\[ERROR\]   [A-Za-z]' "$LOG" | sed 's/^\[ERROR\]   //' | sort -u)

if [ -z "$reds" ]; then
    echo "⚠️  МУТАЦИЯ ПРОШЛА ВХОЛОСТУЮ: не покраснел никто."
    echo
    echo "   По playbook 2.8 это НАХОДКА ПРОЦЕССА, а не повод молча взять другую мутацию."
    echo "   Два разбора, и оба надо записать в docs/review-log.md:"
    echo "     · мутация сформулирована от ЗАМЫСЛА гейта, а не от того, что он читает;"
    echo "     · гейт форвардный — логика под юнит-тестами, сквозняком не доказан."
    summary "$LOG" | sed 's/^/   Итог прогона: /'
    exit 1
fi

echo "Покраснели:"
echo "$reds" | sed 's/^/    /'
echo
summary "$LOG" | sed 's/^/Итог прогона: /'
echo
echo "⚠️  Гейт доказан ТОЛЬКО если в списке выше стоит именно он. Чужой красный,"
echo "    пришедший раньше, означает, что твой гейт мог не отработать вовсе —"
echo "    сверь ЧИСЛА в сообщении, а не только имя класса."
