#!/usr/bin/env bash
#
# Проход 2.8 из docs/review-playbook.md: доказать гейт мутацией.
#
# Зачем отдельный инструмент — три причины, и каждая про вывод, которому нельзя верить.
#
# 1. ОТКАТ МУТАЦИИ СНОСИТ НЕЗАКОММИЧЕННОЕ. Откат — это `git checkout` по файлу, и вместе
#    с мутацией он уносит всё, что в этом файле не закоммичено. Правка при этом не исчезает
#    из головы: коммит, сделанный следом, обещает то, чего в нём уже нет, а заметить это
#    можно только по мутации, которая почему-то никого не покрасила. Поэтому на грязном
#    дереве скрипт отказывается работать.
#
# 2. «ЧТО-ТО ПОКРАСНЕЛО» НЕ ЗНАЧИТ «ПОКРАСНЕЛ ТВОЙ ГЕЙТ». Без -Dmaven.test.failure.ignore=true
#    прогон падает на первом же красном и до поздних гейтов дело не доходит — а красный
#    в логе есть, и его легко принять за свой. Скрипт всегда ставит этот флаг и печатает
#    ИМЕНА покрасневших, а не факт красноты.
#
# 3. ОШИБКА КОМПИЛЯЦИИ — НЕ КРАСНЫЙ ТЕСТ. Сборка с -Werror валится на предупреждении,
#    и в логе это выглядит как «сборка упала», то есть как успех мутации. Гейт при этом
#    не отработал вовсе: до тестов не дошли. Скрипт разводит эти два исхода.
#
# Использование:
#   scripts/mutate.sh <файл> <что-заменить> <на-что>
#
#   Заменяемое — ЛИТЕРАЛ (не регексп) и обязано встречаться в файле ровно один раз:
#   мутация, задевшая два места, доказывает не тот гейт. Многострочный литерал
#   передаётся в кавычках с переводами строк.
#
# Пример (мутация, доказавшая гейт синхронности артефактов) — удалить строку оси
# из матрицы шаблона PR:
#   scripts/mutate.sh .github/pull_request_template.md '| код | | |
#   ' ''
#
set -u

# Каталог скрипта берётся ДО cd: после него `dirname "$0"` уже относителен корню проекта
# и совпадает со `scripts` лишь по случайности.
HERE=$(cd "$(dirname "$0")" && pwd)
cd "$HERE/.." || exit 2

if [ $# -ne 3 ]; then
    # До первой строки без «#»: диапазон, зашитый числом, разъезжается при первой же правке
    # шапки и начинает печатать код вместо справки.
    awk '/^#!/ {next} /^#/ {sub(/^# ?/, ""); print; next} {exit}' "$0"
    exit 2
fi

FILE=$1
OLD=$2
NEW=$3

[ -f "$FILE" ] || { echo "нет такого файла: $FILE"; exit 2; }

# --- 1. Дерево обязано быть чистым -------------------------------------------------
dirty=$(git status --porcelain)
if [ -n "$dirty" ]; then
    echo "ОТКАЗ: дерево грязное — откат мутации унесёт незакоммиченное вместе с ней."
    echo
    echo "$dirty" | sed 's/^/    /'
    echo
    echo "Закоммить или спрячь (git stash), потом повторяй мутацию."
    exit 2
fi

. "$HERE/require-jdk.sh"
require_jdk

LOG=.mutate.log

# Провал отката — единственное, ради чего скрипт написан; молчать о нём нельзя.
restore() {
    git checkout -- "$FILE" \
        || echo "⛔ ОТКАТ НЕ УДАЛСЯ — мутация ОСТАЛАСЬ в $FILE, убери руками" >&2
}
# Обработчик INT в bash не прерывает скрипт: он отрабатывает, и выполнение идёт дальше.
# Без явного exit оборванный прогон дошёл бы до вердикта и изготовил находку из пустого лога.
trap restore EXIT
trap 'restore; exit 130' INT
trap 'restore; exit 143' TERM

# Итоговые строки surefire, а не построчные по классу: у per-class строк тот же формат плюс
# хвост «-- in <класс>», и tail по ним даёт число тестов последнего класса вместо итога.
# Печатаются ВСЕ: surefire запускается дважды, и последняя строка — итог второго исполнения,
# где тестов единицы. Рядом с красным гейтом это читается как «мутация прошла вхолостую».
summary() {
    grep -E 'Tests run: [0-9]+, Failures: [0-9]+, Errors: [0-9]+, Skipped: [0-9]+$' "$1" \
        | sed -E 's/^\[[A-Z]+\] //'
}

# --- 2. Применяем мутацию ----------------------------------------------------------
python3 - "$FILE" "$OLD" "$NEW" <<'PY' || exit 2
import sys
path, old, new = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(path, encoding='utf-8').read()
n = text.count(old)
if n != 1:
    print(f"ОТКАЗ: заменяемое встречается {n} раз(а), нужно ровно 1 — "
          f"мутация на два места доказывает не тот гейт.")
    sys.exit(2)
open(path, 'w', encoding='utf-8').write(text.replace(old, new))
PY

echo "Мутация в $FILE:"
# Шапки дифа отсекаются ПОИМЁННО. Фильтр «второй символ не + и не -» отбросил бы вместе
# с ними любую строку markdown-списка, а доки этого репозитория из них и состоят:
# блок печатался бы пустым ровно там, где мутация чаще всего и ставится.
git diff --unified=0 -- "$FILE" \
    | grep -vE '^(---|\+\+\+|@@|diff |index |new file|deleted file)' \
    | grep -E '^[-+]' | sed 's/^/    /'
echo

# --- 3. Прогон -----------------------------------------------------------------------
started=$(date +%s)
mvn -B clean test -Dmaven.test.failure.ignore=true > "$LOG" 2>&1
echo "Прогон: $(( $(date +%s) - started ))s, лог в $LOG"
echo

# --- 4. Компиляция или тесты? --------------------------------------------------------
# Если тестов не запускалось вовсе — красный дала сборка, а не гейт.
if ! grep -qE '^\[INFO\] Tests run:|^Tests run:' "$LOG"; then
    echo "⛔ ДО ТЕСТОВ ДЕЛО НЕ ДОШЛО — сборка упала раньше. Читается двояко:"
    # WARNING обязателен в выводе: именно он называет файл, строку и ПРИЧИНУ, тогда как
    # строка [ERROR] под -Werror говорит только «warnings found» и повторяется дважды.
    grep -E '^\[WARNING\].*\.java:\[|^\[ERROR\].*\.java|^\[ERROR\] COMPILATION|warnings found' "$LOG" \
        | head -10 | sed 's/^/    /'
    echo
    echo "   · если проверяемый гейт — ТЕСТ: он не отработал ни разу, доказательства нет."
    echo "     Переформулируй мутацию так, чтобы код собирался."
    echo "   · если проверяемый гейт — САМ КОМПИЛЯТОР (-Xlint/-Werror, см. pom.xml): вывод"
    echo "     выше и есть доказательство, и маскировать его нечем — компиляция идёт до"
    echo "     тестов. Но только при условии, что БЕЗ мутации сборка даёт ноль"
    echo "     предупреждений: иначе красный мог прийти от чужого файла. Сверь имя файла."
    exit 3
fi

# --- 5. Кто именно покраснел ---------------------------------------------------------
reds=$(grep -E '^\[ERROR\]   [A-Za-z]' "$LOG" | sed 's/^\[ERROR\]   //' | sort -u)

if [ -z "$reds" ]; then
    echo "⚠️  МУТАЦИЯ ПРОШЛА ВХОЛОСТУЮ: не покраснел никто."
    echo
    echo "   По playbook 2.8 это НАХОДКА ПРОЦЕССА, а не повод молча взять другую мутацию."
    echo "   Два разбора, и оба надо записать в docs/review-log.md:"
    echo "     · мутация сформулирована от ЗАМЫСЛА гейта, а не от того, что он читает;"
    echo "     · гейт форвардный — логика под юнит-тестами, сквозняком не доказан."
    summary "$LOG" | sed 's/^/   Итог прогона: /'
    exit 1
fi

echo "Покраснели:"
echo "$reds" | sed 's/^/    /'
echo
summary "$LOG" | sed 's/^/Итог прогона: /'
echo
echo "⚠️  Гейт доказан ТОЛЬКО если в списке выше стоит именно он. Чужой красный,"
echo "    пришедший раньше, означает, что твой гейт мог не отработать вовсе —"
echo "    сверь ЧИСЛА в сообщении, а не только имя класса."
