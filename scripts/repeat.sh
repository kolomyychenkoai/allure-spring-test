#!/usr/bin/env bash
#
# Ось «повторяемость сьюта» из docs/review-playbook.md: прогнать сборку N раз
# и поймать зависимость от ПОРЯДКА тестов.
#
# Зачем отдельный инструмент. Порядок классов и методов у нас случайный
# (surefire runOrder=random + junit.jupiter.testmethod.order.default=Random),
# поэтому дефект, живущий на конкретной перестановке, виден не всегда.
# Так и нашёлся дефект с временными загрузчиками классов: один красный прогон
# из двадцати, 30 упавших тестов в семи классах, остальные девятнадцать — зелёные.
# Ревью, которое смотрит ОДИН прогон, такое не видит в принципе.
#
# Красный хотя бы раз — это НАХОДКА, а не «перезапусти».
#
# Использование:  scripts/repeat.sh [сколько-прогонов]   (по умолчанию 10)
#
set -u
cd "$(dirname "$0")/.." || exit 2

RUNS=${1:-10}
LOGS=.repeat-logs
mkdir -p "$LOGS"
fail=0

echo "Повторяемость сьюта: $RUNS прогонов — $(date '+%Y-%m-%d %H:%M')"
echo

for i in $(seq 1 "$RUNS"); do
    started=$(date +%s)
    if mvn -B clean test > "$LOGS/run$i.log" 2>&1; then
        status="OK  "
    else
        status="FAIL"
        fail=1
    fi
    # Порядок классов — первое, на что смотрят при разборе: почти всегда дефект
    # зависит от того, что отработало РАНЬШЕ. Пишем префикс порядка рядом с итогом.
    order=$(grep -oE "Running io\.github\.[a-z.]+\.[A-Za-z]+" "$LOGS/run$i.log" \
        | sed 's/.*\.//' | head -5 | tr '\n' ' ')
    printf '%s  run%-3s %4ss  тестов:%-5s  первые классы: %s\n' \
        "$status" "$i" "$(( $(date +%s) - started ))" \
        "$(grep -oE 'Tests run: [0-9]+, Failures: [0-9]+, Errors: [0-9]+, Skipped: [0-9]+$' "$LOGS/run$i.log" \
            | head -1 | sed 's/Tests run: \([0-9]*\).*/\1/')" \
        "$order"

    if [ "$status" = "FAIL" ]; then
        # Что именно упало — сразу, чтобы не листать лог руками
        grep -E "^\[ERROR\]   [A-Za-z]" "$LOGS/run$i.log" | head -5 | sed 's/^/        /'
    fi
done

echo
if [ $fail -eq 0 ]; then
    echo "Все $RUNS прогонов зелёные. Зависимости от порядка не видно."
    echo "⚠️ Это не доказательство её отсутствия: редкая перестановка может не выпасть."
else
    echo "Есть красные. Сравни порядок классов у красных и зелёных прогонов —"
    echo "дефект почти всегда в том, что отработало РАНЬШЕ (логи в $LOGS/)."
fi
exit $fail
