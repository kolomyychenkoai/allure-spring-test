#!/usr/bin/env bash
#
# Механика прохода 2.10 по оси ЯЗЫКА: собирает всё, из-за чего русский текст начинает
# читаться как перевод. Думать по-прежнему человеку — скрипт даёт цифру и материал для чтения.
#
# Два разных дефекта, и ловятся они по-разному:
#   структура — тире и двоеточие вместо сказуемого; берётся счётом, секции 1 и 2;
#   лексика   — слово переведено формально верно, но по-русски так не говорят
#               («статус-онли», «дрейфуют», «сьют»); счётом НЕ берётся, только словарём,
#               секция 3. Словарь накопительный: новую кальку сначала находит чтение,
#               и её сразу дописывают сюда, иначе следующий текст поймает её опять.
#
# Использование:  scripts/prose-scan.sh docs/architecture.md [ревизия]
#
set -u
cd "$(dirname "$0")/.." || exit 2

# ⚠️ Байтовая локаль: BSD grep/sed на кириллице в UTF-8-локали падают, и секции молча
# оказываются пустыми — пустая секция тут читается как «текст чистый», то есть проход врёт.
export LC_ALL=C

FILE=${1:?укажи файл, напр. docs/architecture.md}
REV=${2:-}

if [ -n "$REV" ]; then BODY=$(git show "$REV:$FILE"); else BODY=$(cat "$FILE"); fi
[ -n "$BODY" ] || { echo "✗ пусто: $FILE ${REV:+в ревизии $REV}"; exit 1; }

# Проза = текст без таблиц, блоков кода и строк-отступов. Считать язык по таблицам нельзя:
# там тире стоит законно (это столбцы), и цифра сразу перестаёт что-либо значить.
PROSE=$(printf '%s\n' "$BODY" | awk '
    /^```/ { fence = !fence; next }
    fence || /^\|/ || /^ {4}/ || /^#/ || /^---/ { next }
    # Пустая строка перед пунктом списка: иначе весь список склеится в одно «предложение»
    # на полсотни слов, и секция длинных фраз наберётся мусором (поймано на первом прогоне).
    /^[0-9]+\. / || /^- / || /^\* / { print "" }
    { print }')

hdr() { printf '\n\033[1m%s\033[0m\n%s\n' "$1" "$(printf '─%.0s' $(seq 1 ${#1}))"; }
show() { local out; out=$(cat); if [ -z "$out" ]; then printf '  (пусто)\n'; else printf '%s\n' "$out"; fi; }

echo "Скан языка: $FILE ${REV:+@$REV}"

# ── 1. Цифра ─────────────────────────────────────────────────────────────────
# Единственный измеримый результат прохода: «было столько, стало столько». Тире вместо
# сказуемого — главный признак того, что фраза собрана, а не сказана.
hdr "1. ЦИФРА: чем держится фраза"
printf '%s\n' "$PROSE" | awk '
    { words += NF }
    { line = $0
      dash = gsub(/—/, "—", line); dashes += dash
      colon = gsub(/:/, ":", line); colons += colon }
    END {
        if (words == 0) { print "  (пусто) — сбор прозы сломался"; exit }
        printf "  слов в прозе:        %d\n", words
        printf "  тире «—»:            %d  → %.1f на 100 слов  (ориентир ≤2)\n", dashes, dashes*100/words
        printf "  двоеточий:           %d  → %.1f на 100 слов\n", colons, colons*100/words
        printf "  знаков вместо глагола: %d на %d слов — одно на каждые %d слов\n",
               dashes+colons, words, (dashes+colons ? words/(dashes+colons) : 0)
    }'

# ── 2. Длинные предложения ───────────────────────────────────────────────────
# Русская фраза длиной в 30 слов почти всегда собрана из двух: её надо разделить,
# а не переставить. Печатаем целиком — решает чтение.
hdr "2. ПРОЧИТАТЬ: предложения длиннее 28 слов"
# Звёздочки жирного шрифта снимаем ДО разбивки: «…бывает два.** У MockMvc…» иначе не
# считается концом предложения, и две нормальные фразы склеиваются в одну «длинную».
printf '%s\n' "$PROSE" | awk 'BEGIN { RS = "" } { gsub(/\n/, " "); print }' \
    | sed 's/\*\*//g; s/\([.!?]\) /\1\n/g' | awk '
    { n = NF } n > 28 { printf "  [%d слов] %s\n", n, substr($0, 1, 150) }' | show

# ── 3. Словарь калек ─────────────────────────────────────────────────────────
# Главная секция. Каждое слово слева формально верное — поэтому взгляд за него не цепляется,
# и находится оно только списком. Пополнять при каждой находке.
hdr "3. СЛОВАРЬ КАЛЕК: слово верное, но по-русски так не говорят"
while IFS='|' read -r bad good; do
    [ -z "$bad" ] && continue
    # Без выравнивания по колонкам намеренно: в байтовой локали printf считает БАЙТЫ,
    # а кириллическая буква весит два — колонки разъезжаются тем сильнее, чем длиннее слово.
    printf '%s\n' "$BODY" | grep -n "$bad" | while read -r hit; do
        printf '  стр. %-4s %s → %s\n' "${hit%%:*}" "$bad" "$good"
    done
done <<'DICT' | show
статус-онли|только статус
проигрывание|повтор
дрейфу|расходятся с кодом
обеднённ|неполный
оснастк|инструменты
сьют|прогон
фолбэк|подстраховка
двух родов|двух видов
родная точка|базовая версия
внутренност|внутренний код
вцепля|цепляется
сыпет|сыплет
эмфаз|выделения
уносит строку|теряется строка
на сломанном|когда сбор сломался
DICT

# ── 4. Канцелярит ────────────────────────────────────────────────────────────
hdr "4. КАНЦЕЛЯРИТ: оборот вместо глагола"
printf '%s\n' "$PROSE" | grep -inE 'является|осуществля|данный |данного |в рамках|с целью|представляет собой|носит характер|в связи с|за счёт того|в случае если' | show

# ── 5. Частотник личных тиков ────────────────────────────────────────────────
# Не находки, а лупа: два «ровно» на страницу нормальны, восемь — тик, который читается
# как навязчивость.
hdr "5. ЧАСТОТНИК: слова-тики"
for w in ровно именно 'то есть' просто 'как раз' иначе 'при этом' 'тем самым' вообще; do
    n=$(printf '%s\n' "$PROSE" | grep -oi "$w" | grep -c '')
    [ "$n" -gt 2 ] && printf '  %-12s %s\n' "$w" "$n"
done | show

# ── 6. Телеграфные зачины ────────────────────────────────────────────────────
# «Время: …», «Задача — …», «Семь шагов — столько стоит …»: подлежащее, знак, и дальше
# пояснение без сказуемого. По-русски так пишут заголовки, а не абзацы.
hdr "6. ЗАЧИНЫ БЕЗ СКАЗУЕМОГО: тире или двоеточие в первых четырёх словах"
printf '%s\n' "$PROSE" | grep -nE '^[^ ]+( [^ ]+){0,3}( — |: )' | sed 's/^/  /' | cut -c1-140 | show

cat <<'HINT'

Чего скрипт сделать не может — и без чего проход НЕ закрыт (docs/review-playbook.md, 2.10):
  1. новая калька, которой ещё нет в словаре, — её находит только чтение вслух;
     найденную ДОПИСАТЬ в секцию 3 сразу, иначе следующий текст поймает её снова;
  2. смысл после правки языка — его держит scripts/doc-facts.sh (отпечаток фактов);
  3. цифра «было/стало» из секции 1 — назвать вслух, иначе правка недоказуема.
HINT
